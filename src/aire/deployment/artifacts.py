"""Deployment artifact generation: Dockerfile, entrypoint, env template."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field

from aire._version import __version__

_DOCKERFILE = """\
FROM python:3.12-slim

LABEL org.opencontainers.image.title="aire deployment"
LABEL org.opencontainers.image.description="Generated by the aire AI creation library"

WORKDIR /app
COPY requirements.in /app/requirements.in
RUN pip install --no-cache-dir -r requirements.in

COPY . /app

EXPOSE 8000
HEALTHCHECK --interval=30s --timeout=5s CMD python -c "import urllib.request;urllib.request.urlopen('http://localhost:8000/health')"

CMD ["uvicorn", "entrypoint:app", "--host", "0.0.0.0", "--port", "8000"]
"""

_ENTRYPOINT = """\
\"\"\"Generated ASGI entrypoint; initialize sync user factories off the server loop.\"\"\"

import asyncio
from contextlib import asynccontextmanager

from fastapi import FastAPI
from app import build_target
from aire.deployment import create_app


@asynccontextmanager
async def lifespan(app):
    target = await asyncio.to_thread(build_target)
    service = create_app(target, close_target=True)
    app.mount("/", service)
    from aire.ai import default_runtime
    try:
        async with service.router.lifespan_context(service):
            yield
    finally:
        await default_runtime().aclose()


app = FastAPI(lifespan=lifespan, docs_url=None, redoc_url=None, openapi_url=None)
"""

_APP_SCAFFOLD = """\
\"\"\"User application entry — edit build_target() then redeploy.

entrypoint.py imports build_target and wraps it with aire.deployment.create_app.

When scale-pack sidecars are enabled, compose/k8s set:
  AIRE_REDIS_URL=redis://redis:6379/0
  AIRE_DATABASE_URL=postgresql://aire:aire@postgres:5432/aire
\"\"\"

from __future__ import annotations

import logging
import os
from typing import Any

_log = logging.getLogger("aire.app")


def build_target() -> Any:
    \"\"\"Return an Agent, Knowledge, Model, or Team for create_app().\"\"\"
    from aire import AI

    runtime = AI.configure()
    model = AI.models.use_sync(runtime.settings.model.ref)
    redis_url = os.environ.get("AIRE_REDIS_URL")
    if redis_url:
        try:
            model = AI.models.cache(model, backend="redis", url=redis_url)
            runtime.resources.track_resource("deployment-redis-cache", model.backend)
            from redis import Redis
            with Redis.from_url(redis_url, socket_connect_timeout=5, socket_timeout=5) as probe:
                probe.ping()
            _log.info("model cache wired to AIRE_REDIS_URL")
        except Exception:
            if os.environ.get("AIRE_ALLOW_OFFLINE_FALLBACK") != "1":
                raise
            model = AI.models.use_sync(runtime.settings.model.ref)
            _log.warning("Configured Redis unavailable; explicit offline fallback enabled")

    database_url = os.environ.get("AIRE_DATABASE_URL")
    if database_url:
        try:
            from aire.rag.pgvector import PgVectorStore
            store = PgVectorStore(database_url)
            knowledge = AI.rag.create(store=store, model=model)
            _log.info("Knowledge wired to PgVectorStore via AIRE_DATABASE_URL")
            return knowledge
        except Exception:
            if os.environ.get("AIRE_ALLOW_OFFLINE_FALLBACK") != "1":
                raise
            _log.warning("Configured Postgres unavailable; explicit offline fallback enabled")

    return model


# Optional: build FastAPI app directly for local `uvicorn app:app`
def create_app_local() -> Any:
    from aire.deployment import create_app

    return create_app(build_target())
"""

