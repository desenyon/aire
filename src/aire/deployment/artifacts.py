class DeployArtifacts(BaseModel):
    """Files generated for a deployment."""

    directory: str
    files: list[str] = Field(default_factory=list)


def generate_artifacts(
    directory: str | Path,
    *,
    project: str = "aire-app",
    extra_requirements: list[str] | None = None,
    wheel: str | Path | None = None,
) -> DeployArtifacts:
    """Write deployment inputs, preserving the user app and extra requirements."""
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    import re
    import shutil
    import zipfile
    from email.parser import BytesParser

    from aire.core.errors import ConfigurationError

    dockerfile = _DOCKERFILE
    if wheel is not None:
        source_wheel = Path(wheel).resolve()
        try:
            with zipfile.ZipFile(source_wheel) as archive:
                metadata_path = next(
                    name for name in archive.namelist() if name.endswith(".dist-info/METADATA")
                )
                metadata = BytesParser().parsebytes(archive.read(metadata_path))
                if metadata["Name"] != "aire-ai" or metadata["Version"] != __version__:
                    raise ValueError("wheel version/distribution mismatch")
        except (OSError, ValueError, StopIteration, zipfile.BadZipFile) as exc:
            raise ConfigurationError(
                "provide an aire-ai wheel matching the runtime version", code="deploy.wheel_invalid"
            ) from exc
        wheel_directory = target / "wheels"
        wheel_directory.mkdir(exist_ok=True)
        shutil.copy2(source_wheel, wheel_directory / source_wheel.name)
        dockerfile = dockerfile.replace(
            "COPY requirements.in", "COPY wheels /app/wheels\nCOPY requirements.in"
        ).replace(
            "pip install --no-cache-dir", "pip install --no-cache-dir --find-links=/app/wheels"
        )
    existing = target / "requirements.in"
    lines = existing.read_text().splitlines() if existing.is_file() else []
    retained = []
    for line in lines:
        match = re.fullmatch(r"(aire[-_]ai(?:\[[^]]+\])?)(?:[<>=!~].*)?", line.strip())
        retained.append(f"{match.group(1)}=={__version__}" if match else line)
    requirements = list(
        dict.fromkeys([f"aire-ai[serve]=={__version__}", *(extra_requirements or []), *retained])
    )
    files: list[str] = []
    for name, content in {
        "Dockerfile": dockerfile,
        "entrypoint.py": _ENTRYPOINT,
        "app.py": _APP_SCAFFOLD,
        ".env.template": _ENV_TEMPLATE.format(project=project),
        "requirements.in": "\n".join(requirements) + "\n",
    }.items():
        path = target / name
        # Do not clobber an existing user app.py
        if name == "app.py" and path.exists():
            files.append(str(path))
            continue
        path.write_text(content)
        files.append(str(path))
    return DeployArtifacts(directory=str(target), files=files)


def describe() -> dict[str, Any]:
    return {
        "kind": "deployment",
        "artifacts": [
            "Dockerfile",
            "entrypoint.py",
            "app.py",
            ".env.template",
            "requirements.in",
        ],
        "endpoints": ["/health", "/ready", "/manifest", "/metrics"],
        "scale_env": ["AIRE_REDIS_URL", "AIRE_DATABASE_URL"],
    }


def lock_requirements(
    directory: str | Path,
    *,
    python_version: str = "3.12",
    python_platform: str = "linux",
    find_links: str | Path | None = None,
) -> Path:
    """Resolve hashed deployment dependencies with uv for an explicit target.

    Install uv separately. A local wheel directory can supply an unreleased Aire
    version. Existing Dockerfile switches to the lock only after resolution succeeds.
    """
    import shutil
    import subprocess
    import tempfile

    from aire.core.errors import ConfigurationError

    executable = shutil.which("uv")
    if executable is None:
        raise ConfigurationError("deployment locking requires uv on PATH", code="deploy.uv_missing")
    target = Path(directory).resolve()
    source = target / "requirements.in"
    output = target / "requirements.lock"
    if not source.is_file():
        raise ConfigurationError(
            "generate requirements.in before locking", code="deploy.requirements_missing"
        )
    command = [
        executable,
        "pip",
        "compile",
        str(source),
        "--python-version",
        python_version,
        "--python-platform",
        python_platform,
        "--generate-hashes",
        "--output-file",
        str(output),
    ]
    if find_links is not None:
        command.extend(["--find-links", str(Path(find_links).resolve())])
    try:
        with tempfile.TemporaryDirectory(prefix=".aire-lock-", dir=target) as staging:
            staged = Path(staging) / "requirements.lock"
            command[command.index("--output-file") + 1] = str(staged)
            subprocess.run(command, check=True, capture_output=True, timeout=300, cwd=target)  # noqa: S603
            staged.replace(output)
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
        raise ConfigurationError(
            "deployment dependency resolution failed", code="deploy.lock_failed"
        ) from exc
    dockerfile = target / "Dockerfile"
    if dockerfile.is_file():
        content = dockerfile.read_text().replace("requirements.in", "requirements.lock")
        if "--require-hashes" not in content:
            content = content.replace(
                "pip install --no-cache-dir", "pip install --no-cache-dir --require-hashes"
            )
        dockerfile.write_text(content)
    return output
