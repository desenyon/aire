class DeployArtifacts(BaseModel):
    """Files generated for a deployment."""

    directory: str
    files: list[str] = Field(default_factory=list)


def generate_artifacts(
    directory: str | Path,
    *,
    project: str = "aire-app",
    extra_requirements: list[str] | None = None,
) -> DeployArtifacts:
    """Write Dockerfile, entrypoint, app scaffold, env template and lock file."""
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    requirements = [f"aire-ai[serve]=={__version__}", *(extra_requirements or [])]
    files: list[str] = []
    for name, content in {
        "Dockerfile": _DOCKERFILE,
        "entrypoint.py": _ENTRYPOINT,
        "app.py": _APP_SCAFFOLD,
        ".env.template": _ENV_TEMPLATE.format(project=project),
        "requirements.in": "\n".join(requirements) + "\n",
    }.items():
        path = target / name
        # Do not clobber an existing user app.py
        if name == "app.py" and path.exists():
            files.append(str(path))
            continue
        path.write_text(content)
        files.append(str(path))
    return DeployArtifacts(directory=str(target), files=files)


def describe() -> dict[str, Any]:
    return {
        "kind": "deployment",
        "artifacts": [
            "Dockerfile",
            "entrypoint.py",
            "app.py",
            ".env.template",
            "requirements.in",
        ],
        "endpoints": ["/health", "/ready", "/manifest", "/metrics"],
        "scale_env": ["AIRE_REDIS_URL", "AIRE_DATABASE_URL"],
    }


def lock_requirements(
    directory: str | Path,
    *,
    python_version: str = "3.12",
    python_platform: str = "linux",
    find_links: str | Path | None = None,
) -> Path:
    """Resolve hashed deployment dependencies with uv for an explicit target.

    Install uv separately. A local wheel directory can supply an unreleased Aire
    version. Existing Dockerfile switches to the lock only after resolution succeeds.
    """
    import shutil
    import subprocess

    from aire.core.errors import ConfigurationError

    executable = shutil.which("uv")
    if executable is None:
        raise ConfigurationError("deployment locking requires uv on PATH", code="deploy.uv_missing")
    target = Path(directory).resolve()
    source = target / "requirements.in"
    output = target / "requirements.lock"
    if not source.is_file():
        raise ConfigurationError(
            "generate requirements.in before locking", code="deploy.requirements_missing"
        )
    command = [
        executable,
        "pip",
        "compile",
        str(source),
        "--python-version",
        python_version,
        "--python-platform",
        python_platform,
        "--generate-hashes",
        "--output-file",
        str(output),
    ]
    if find_links is not None:
        command.extend(["--find-links", str(Path(find_links).resolve())])
    try:
        subprocess.run(command, check=True, capture_output=True, timeout=300)  # noqa: S603
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
        raise ConfigurationError(
            "deployment dependency resolution failed", code="deploy.lock_failed"
        ) from exc
    dockerfile = target / "Dockerfile"
    if dockerfile.is_file():
        content = dockerfile.read_text().replace("requirements.in", "requirements.lock")
        content = content.replace(
            "pip install --no-cache-dir -r", "pip install --no-cache-dir --require-hashes -r"
        )
        dockerfile.write_text(content)
    return output
